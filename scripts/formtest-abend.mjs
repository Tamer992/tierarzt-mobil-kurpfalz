// Funktionstest Terminanfrage: Vorbelegung von der Startseite, Postleitzahl, Fehler, Korrektur, gesendet
import { chromium } from 'playwright';
const basis = process.argv[2] || 'http://127.0.0.1:4391';
const b = await chromium.launch(); const s = await (await b.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })).newPage();
const fehler = []; s.on('console', (m) => { if (m.type() === 'error') fehler.push(m.text()); }); s.on('pageerror', (e) => fehler.push(e.message));
const ok = (bed, text) => console.log(bed ? 'ok  ' : 'FEHLER', text);
await s.goto(basis + '/abend/');
await s.check('input[name="tier"][value="katze"]', { force: true });
await s.selectOption('#anlass', 'Durchfall und Erbrechen');
await s.fill('#anlass-text', 'Seit heute früh');
await s.click('.vorauswahl button[type="submit"]');
await s.waitForURL(/termin/);
ok(await s.isChecked('input[name="tier"][value="Katze"]'), 'Katze übernommen');
ok((await s.inputValue('#f-anlass')) === 'Durchfall und Erbrechen', 'Anlass übernommen');
ok((await s.inputValue('#f-anlass_text')) === 'Seit heute früh', 'Beschreibung übernommen');
await s.click('button[type="submit"]');
ok(await s.isVisible('#fehlerliste'), 'Fehlerübersicht erscheint');
const n = await s.locator('#fehlerliste li').count(); ok(n === 6, `Fehler gezählt: ${n} (Straße, PLZ, Ort, Name, Telefon, Datenschutz)`);
ok(await s.evaluate(() => document.activeElement.id === 'fehlerliste'), 'Fokus auf der Übersicht');
await s.click('#fehlerliste a[data-ziel="plz"]'); ok(await s.evaluate(() => document.activeElement.id === 'f-plz'), 'Link springt ins Feld');
await s.fill('#f-plz', '68159');
ok((await s.inputValue('#f-ort')) === 'Mannheim', 'Ort aus Postleitzahl ergänzt');
ok(await s.locator('#plz-fehler').isHidden(), 'PLZ-Fehler verschwindet beim Korrigieren');
ok((await s.textContent('#plz-ausserhalb')).includes('Mannheim'), 'Hinweis Einsatzgebiet');
await s.fill('#f-plz', '10000'); ok((await s.textContent('#plz-ausserhalb')).includes('nicht auf meiner Liste'), 'Postleitzahl außerhalb erkannt');
await s.fill('#f-plz', '68159');
await s.check('input[name="wann"][value="An einem bestimmten Tag"]', { force: true });
ok(await s.isVisible('#f-datum'), 'Tag erscheint bei bestimmtem Tag');
await s.check('input[name="tier"][value="Anderes Tier"]', { force: true }); ok(await s.isVisible('#f-tier_anderes'), 'Welches Tier erscheint');
await s.check('input[name="tier"][value="Katze"]', { force: true }); ok(await s.isHidden('#f-tier_anderes'), 'Welches Tier verschwindet');
await s.fill('#f-strasse', 'Beispielweg 4'); await s.fill('#f-name', 'Test'); await s.fill('#f-telefon', '12'); await s.fill('#f-email', 'a@b');
console.log('  Haken vorher', await s.isChecked('#f-datenschutz')); await s.click('.haken__text'); console.log('  Haken nachher', await s.isChecked('#f-datenschutz'));
await s.click('button[type="submit"]');
const rest = await s.locator('#fehlerliste li').allTextContents(); ok(rest.length === 3, 'noch offen: ' + rest.join(' / '));
await s.fill('#f-telefon', '0170 1234567'); await s.fill('#f-email', 'a@b.de');
const morgen = new Date(Date.now() + 86400000).toISOString().slice(0, 10); await s.fill('#f-datum', morgen);
await s.click('button[type="submit"]');
ok((await s.getAttribute('button[type="submit"]', 'aria-disabled')) === 'true', 'Knopf deaktiviert beim Senden');
await s.waitForSelector('#gesendet:not([hidden])');
ok((await s.textContent('#gesendet')).includes('0170 1234567'), 'Gesendet mit Rückrufnummer');
console.log((await s.locator('.gesendet__liste').innerText()).replace(/\n/g, ' | '));
ok(!fehler.length, 'Konsole ohne Fehler ' + fehler.join(' '));
await b.close();
